import SwiftUI

enum CompanionTheme {
    static let accent = Color.blue
    static let appBackground = Color(uiColor: .systemGroupedBackground)
    static let panel = Color(uiColor: .secondarySystemGroupedBackground)
    static let panelAlt = Color(uiColor: .tertiarySystemGroupedBackground)
    static let raised = Color(uiColor: .secondarySystemBackground)
    static let border = Color.primary.opacity(0.14)
    static let borderSoft = Color.primary.opacity(0.08)
    static let success = Color.green
    static let warning = Color.orange
    static let danger = Color.red
}
